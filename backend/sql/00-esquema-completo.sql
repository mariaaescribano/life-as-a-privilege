-- ── Vista de estadísticas del estudio ────────────────────────────────────
create or replace view public.estudio_stats as
select
  planeta,
  eje,
  posicion,
  pregunta_id,
  count(*)::int                              as total,
  count(*) filter (where respuesta)::int     as si,
  count(*) filter (where not respuesta)::int as no
from public.estudio_respuesta
group by planeta, eje, posicion, pregunta_id;

-- ── RLS: activado en TODAS las tablas, sin políticas (solo entra el backend) ──
do $$
declare t record;
begin
  for t in
    select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity
  loop
    execute format('alter table public.%I enable row level security', t.relname);
  end loop;
end $$;

